export function allEmojis() {
  const out = []
  const seen = new Set()
  for (const cat of EMOJI_CATEGORIES) {
    for (const e of cat.emojis) {
      if (!e || seen.has(e)) continue
      seen.add(e)
      out.push(e)
    }
  }
  return out
}

export function searchEmojis(query, { category = null, limit = 500 } = {}) {
  const q = String(query || '').trim().toLowerCase()
  let pool = []
  if (category && category !== '__all' && category !== '__recent') {
    const cat = EMOJI_CATEGORIES.find((c) => c.key === category)
    pool = cat ? [...cat.emojis] : []
  } else {
    pool = allEmojis()
  }
  if (!q) return pool.slice(0, limit)
  // Emoji search is weak without names — keep matches that include the query as substring (rare)
  // and also filter category label matches by returning full category if label matches.
  const catHit = EMOJI_CATEGORIES.find((c) => c.label.toLowerCase().includes(q) || c.key.includes(q))
  if (catHit && (!category || category === '__all')) {
    return catHit.emojis.slice(0, limit)
  }
  return pool.filter((e) => e.includes(q)).slice(0, limit)
}

const EMOJI_RECENTS_KEY = 'voicecraft:emojiRecents'
const MAX_EMOJI_RECENTS = 24

export function getRecentEmojis() {
  try {
    const raw = localStorage.getItem(EMOJI_RECENTS_KEY)
    if (!raw) return []
    const arr = JSON.parse(raw)
    return Array.isArray(arr) ? arr.filter((e) => typeof e === 'string').slice(0, MAX_EMOJI_RECENTS) : []
  } catch {
    return []
  }
}

export function pushRecentEmoji(emoji) {
  if (!emoji || typeof emoji !== 'string') return getRecentEmojis()
  const next = [emoji, ...getRecentEmojis().filter((e) => e !== emoji)].slice(0, MAX_EMOJI_RECENTS)
  try {
    localStorage.setItem(EMOJI_RECENTS_KEY, JSON.stringify(next))
  } catch { /* ignore */ }
  return next
}
